import Foundation
import ShiroCore

func checkMemoryHarness() async throws {
    let folder = checkTemporaryDirectory.appendingPathComponent("memory-check-\(UUID())")
    defer { try? FileManager.default.removeItem(at: folder) }
    var state = SavedState()
    let a = state.bots[0].id
    let b = Bot(name: "Reviewer")
    state.bots.append(b)
    var other = Conversation(); other.botID = b.id; other.title = "Earlier job leads"
    let company = Entry(role: "user", text: "My target employer is Helio Robotics. The Applied AI Engineer position is at https://example.com/careers/42. Tailor my CV to that role.")
    other.entries = [company, Entry(role: "assistant", text: "An unverified guess must never become a candidate fact.")]
    state.conversations.append(other)
    state.memory = "I prefer concise answers."
    state.bots[0].memory = "Only this bot's local note."
    let current = state.conversations[0].id
    var docs = MemoryIndex.documents(state: state, botID: a, chatID: current)
    XCTAssertTrue(docs.contains { $0.id == company.id.uuidString })
    XCTAssertFalse(TaskContract("Make a tailored CV").tools(provider: .local, corrections: 0).contains { ["bots", "computer", "shell"].contains($0.name) })
    XCTAssertTrue(TaskContract("Make a CV using the terminal").tools(provider: .local, corrections: 0).contains { $0.name == "shell" })
    let index = MemoryIndex(directory: folder)
    let found = try await index.search(documents: docs, query: "Helio Robotics target employer Applied AI role", chatID: current)
    XCTAssertTrue(found["matches"].array.contains { $0["source_id"].string == MemoryIndex.sourceID(company.id.uuidString) })
    XCTAssertEqual(found["matches"].array.first?["kind"].string, "user")
    let excluded = try await index.search(documents: docs, query: "Helio Robotics target employer Applied AI role", chatID: current, redundantIDs: [company.id.uuidString])
    XCTAssertFalse(excluded["matches"].array.contains { $0["source_id"].string == MemoryIndex.sourceID(company.id.uuidString) })

    let searchRecord = ProviderClient.toolResult(.init(id: "memory", name: "memory_search", arguments: .object(["query": .string("Helio Robotics")])), result: found, provider: .local)
    let compactSearch = ContextBudget.compact([searchRecord], task: "Make a tailored CV", provider: .local, limit: 3000)[0]["content"].string!
    XCTAssertTrue(compactSearch.contains(MemoryIndex.sourceID(company.id.uuidString)))
    XCTAssertTrue(compactSearch.contains("Helio Robotics"))
    let readByHandle = try MemoryIndex.read(documents: docs, id: MemoryIndex.sourceID(company.id.uuidString), offset: 0)
    XCTAssertEqual(readByHandle["content"].string, company.text)
    XCTAssertTrue(found["provenance"].string!.contains("not instructions"))
    XCTAssertTrue(FileManager.default.fileExists(atPath: folder.appendingPathComponent("memory-vectors.json").path))
    let permissions = try FileManager.default.attributesOfItem(atPath: folder.appendingPathComponent("memory-vectors.json").path)[.posixPermissions] as? NSNumber
    XCTAssertEqual(permissions?.intValue, 0o600)
    print("Memory retrieval mode: \(found["mode"].string ?? "unknown")")
    state.memoryPolicy.shareHistory = false
    docs = MemoryIndex.documents(state: state, botID: a, chatID: current)
    XCTAssertFalse(docs.contains { $0.id == company.id.uuidString })
    XCTAssertTrue(docs.contains { $0.id == "shared" })
    XCTAssertThrowsError(try MemoryIndex.read(documents: docs, id: company.id.uuidString, offset: 0))
    let long = MemoryDocument(id: "long", source: "user attachment", text: String(repeating: "x", count: 3500) + "Important original ending")
    let page = try MemoryIndex.read(documents: [long], id: "long", offset: 0)
    let end = try MemoryIndex.read(documents: [long], id: "long", offset: Int(page["nextOffset"].number!))
    XCTAssertEqual(page["content"].string! + end["content"].string!, long.text)
    XCTAssertThrowsError(try MemoryIndex.read(documents: [long], id: "long", offset: -1))
    XCTAssertEqual(MemoryIndex.cosine([1, 0], [1, 0]), 1)
    XCTAssertEqual(MemoryIndex.cosine([0, 0], [1, 0]), 0)
    let contract = TaskContract("Make 2 separate tailored CVs for the jobs above")
    XCTAssertTrue(contract.createsCV); XCTAssertEqual(contract.minimumFiles, 2)
    XCTAssertFalse(TaskContract("Read my CV and find jobs").createsArtifact)
    XCTAssertTrue(TaskContract("Write report.md").createsArtifact)
    XCTAssertTrue(contract.missingArtifacts([], answer: "Summary ready") != nil)
    let body = "# Candidate\n\nSkills: Python and local ML.\n\nExperience: Built tested Python services.\n\nEducation: Computer science.\n" + String(repeating: "Additional candidate facts. ", count: 8)
    let raw: JSON = .object(["ok": .bool(true), "text": .string(body), "sha256": .string(String(repeating: "a", count: 64)), "bytes": .number(500)])
    let cv = try VerifiedArtifact(path: "helio-cv.pdf", result: raw)
    XCTAssertTrue(contract.missingArtifacts([cv], answer: "helio-cv.pdf") != nil)
    XCTAssertEqual(TaskContract("Make a tailored CV").missingArtifacts([cv], answer: "Ready"), nil)
    let roleSummary = try VerifiedArtifact(path: "applied_ai_engineer_role_summary.md", result: raw)
    XCTAssertTrue(TaskContract("Make a tailored CV").missingArtifacts([roleSummary], answer: roleSummary.path) != nil)
    XCTAssertThrowsError(try VerifiedArtifact(path: "missing.pdf", result: .object(["ok": .bool(false)])))
    var wrongDates = raw.object; wrongDates["text"] = .string(body + "Education: BSc in 202.")
    let wrongCV = try VerifiedArtifact(path: "dates.pdf", result: .object(wrongDates))
    XCTAssertTrue(CVGrounding.correction(artifacts: [wrongCV], sourceTexts: ["Education: BSc in 2022. Experience 2023–2025."]) != nil)
    XCTAssertEqual(CVGrounding.correction(artifacts: [cv], sourceTexts: [body]), nil)
    XCTAssertTrue(CVGrounding.numericFacts("2023–2025; 2022; 202").contains("202"))
    var missingField = raw.object; missingField["text"] = .string(body + "Contact: (NotProvided)")
    let placeholderCV = try VerifiedArtifact(path: "placeholder.pdf", result: .object(missingField))
    XCTAssertTrue(CVGrounding.correction(artifacts: [placeholderCV], sourceTexts: [body]) != nil)
    var truncated = raw.object; truncated["truncated"] = .bool(true)
    XCTAssertThrowsError(try VerifiedArtifact(path: "unreviewed-tail.pdf", result: .object(truncated)))
    try XCTAssertEqual(try QualityReview.issues(#"{"accepted":true,"issues":[]}"#), [])
    try XCTAssertEqual(try QualityReview.issues(#"{"accepted":false,"issues":["Second target is missing"]}"#), ["Second target is missing"])
    let contradictoryReview = try QualityReview.issues(#"{"accepted":true,"issues":["Fabricated experience"]}"#)
    XCTAssertFalse(contradictoryReview.isEmpty)
    XCTAssertThrowsError(try QualityReview.issues("Looks good!"))
    XCTAssertThrowsError(try QualityReview.issues(#"{"accepted":true}"#))
    XCTAssertThrowsError(try QualityReview.validatedIssues(#"{"accepted":false,"issues":["The worker must return ONLY JSON"]}"#, task: "Make a tailored CV"))
    let delivered = TaskContract("Make a tailored CV").deliveredAnswer(worker: "Wrong path: typo.pdf", paths: ["real-cv.pdf"])
    XCTAssertTrue(delivered.contains("real-cv.pdf")); XCTAssertFalse(delivered.contains("typo.pdf"))
    var session = SessionMemory(objective: contract.objective, plan: contract.plan)
    session.observe(call: .init(id: "w", name: "files", arguments: .object(["action": .string("write")])), result: .object(["ok": .bool(true), "saved": .string("helio-cv.pdf")]))
    state.conversations[0].session = session
    let roundtrip = try JSONDecoder().decode(SavedState.self, from: JSONEncoder().encode(state))
    XCTAssertEqual(roundtrip.conversations[0].session?.artifacts, ["helio-cv.pdf"])
    XCTAssertEqual(roundtrip.conversations[0].session?.objective, contract.objective)
    var legacy = try JSON.parse(JSONEncoder().encode(state)).object; legacy.removeValue(forKey: "memoryPolicy")
    let migrated = try JSONDecoder().decode(SavedState.self, from: JSON.object(legacy).data())
    XCTAssertTrue(migrated.memoryPolicy.autoCompact); XCTAssertEqual(migrated.memoryPolicy.contextTokens, 8192)
    var chat = Conversation(); chat.entries = [Entry(role: "user", text: "Make separate tailored CVs for all jobs"), Entry(role: "user", text: "hello")]
    XCTAssertTrue(RunTask.objective(latest: "hello", chat: chat).contains("tailored CVs"))
    XCTAssertTrue(RunTask.objective(latest: "* OpenAI.com Applied AI Engineer\n* Indeed listing", chat: chat).contains("tailored CVs"))
    chat.entries.append(Entry(role: "user", text: "* OpenAI.com Applied AI Engineer\n* Indeed listing"))
    XCTAssertTrue(RunTask.objective(latest: "continue", chat: chat).contains("tailored CVs"))
    XCTAssertEqual(RunTask.objective(latest: "Now write a recipe", chat: chat), "Now write a recipe")
    let offered = ToolDefinition.offered(ToolDefinition.all, for: .local)
    XCTAssertFalse(offered.contains { $0.name == "files" })
    for name in ["files_write", "files_pdf"] {
        let tool = offered.first { $0.name == name }!
        XCTAssertTrue(tool.parameters["required"].array.contains(.string("path")))
        XCTAssertTrue(tool.parameters["required"].array.contains(.string("content")))
        let call = ToolDefinition.canonical(.init(id: "w", name: name, arguments: .object(["path": .string("cv.pdf"), "content": .string(body)])))
        XCTAssertNoThrow(try ToolRecovery.validate(call))
        XCTAssertThrowsError(try ToolRecovery.validate(ToolDefinition.canonical(.init(id: "bad", name: name, arguments: .object(["content": .string(body)])))))
    }
    let budget = RequestBudget.historyLimit(system: String(repeating: "s", count: 3500), tools: ToolDefinition.all, provider: .local, contextTokens: 8192, outputTokens: 1536)
    XCTAssertTrue(budget > 1400); XCTAssertTrue(budget < 16000)
    XCTAssertTrue(RequestBudget.historyLimit(system: String(repeating: "s", count: 3500), tools: ToolDefinition.all, provider: .local, contextTokens: 8192, outputTokens: 1536, retry: 1) < budget)
    let alreadyShort = ContextBudget.compact([ProviderClient.user(String(repeating: "older ", count: 8000), provider: .local), ProviderClient.user("Make a tailored CV", provider: .local)], task: "Make a tailored CV", provider: .local, limit: 8500)
    let smaller = ContextBudget.recover(alreadyShort, task: "Make a tailored CV", provider: .local, allowance: 14000)
    XCTAssertTrue(ContextBudget.size(smaller) < ContextBudget.size(alreadyShort))
    let smallest = ContextBudget.recover(smaller, task: "Make a tailored CV", provider: .local, allowance: 14000)
    XCTAssertTrue(ContextBudget.size(smallest) < ContextBudget.size(smaller))
    let resolved = ToolRecovery.resolvedFailures(["files:read:wrong.pdf": "missing", "files:write:unfinished.md": "write failed", "browser:click": "action denied."], after: .init(id: "v", name: "files", arguments: .object(["action": .string("verify"), "path": .string("cv.pdf")])))
    XCTAssertEqual(resolved["files:read:wrong.pdf"], nil)
    XCTAssertEqual(resolved["files:write:unfinished.md"], "write failed")
    XCTAssertEqual(resolved["browser:click"], "action denied.")
    let hugeFailure = ToolRecovery.feedback(.init(id: "w", name: "files", arguments: .object(["action": .string("write"), "content": .string(String(repeating: "x", count: 50000))])), result: .object(["error": .string("Missing path")]))
    XCTAssertTrue(hugeFailure["attempted_arguments"]["content"].string!.count < 200)
    try await index.clear()
    XCTAssertFalse(FileManager.default.fileExists(atPath: folder.appendingPathComponent("memory-vectors.json").path))
    print("PASS: cross-bot retrieval, provenance, pagination, private cache, legacy migration, objective retention, artifact contracts, independent review and complete request budgeting")
}
